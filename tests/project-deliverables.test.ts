import { mkdtemp, mkdir, readFile, readdir, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { createProjectDeliverables, loadArtifactSourceRoots } from '@/scripts/project-deliverables.cjs';

let directory: string;
let root: string;
let cache: string;
const trace = { runId: 'run-delivery', taskId: 'task-delivery', nodeId: 'generate' };
beforeEach(async () => {
  directory = await mkdtemp(path.join(tmpdir(), 'studio-deliverables-'));
  root = path.join(directory, 'project'); cache = path.join(directory, 'tool-output');
  await mkdir(root); await mkdir(cache, { recursive: true });
});
afterEach(async () => { await rm(directory, { recursive: true, force: true }); });

function session(writeAllowed = true, inputs = {}) {
  return createProjectDeliverables({ rootPath: root, writeAllowed, approvedSourceRoots: [cache], trace, inputs, attempt: 2, iteration: 1 });
}
function result(output: unknown, artifacts: Array<{ path: string; description: string }> = []) {
  return JSON.stringify({ trace, outputs: [{ key: 'result', valueJson: JSON.stringify(output) }], artifacts, summary: 'Done.', selectedCondition: '' });
}
function files(output: unknown, paths: string[]) {
  return result(output, paths.map((file) => ({ path: file, description: `Delivered file: ${path.basename(file)}` })));
}

describe('project delivery for all workflow file types', () => {
  it('verifies edits to existing project files and preserves their location', async () => {
    const file = path.join(root, 'app.ts'); await writeFile(file, 'old');
    const task = await session(); await writeFile(file, 'edited');
    const output = JSON.parse(await task.finish(result({ updated_files: ['app.ts'] }, [{ path: file, description: 'Updated application' }])));
    expect(await readFile(file, 'utf8')).toBe('edited');
    expect(output.artifacts).toHaveLength(1);
    expect(output.artifacts[0].path).toBe(file);
    expect(JSON.parse(output.outputs[0].valueJson).updated_files).toEqual([file]);
  });

  it('exports new generated images into the project and rewrites downstream references', async () => {
    const task = await session(); const image = path.join(cache, 'screen.png');
    await writeFile(image, 'generated image bytes');
    const output = JSON.parse(await task.finish(files({ screens: [{ asset_path: image }] }, [image])));
    const file = output.artifacts[0].path;
    expect(path.relative(root, file)).not.toMatch(/^\.\./);
    expect(file).toContain(path.join('artifacts', trace.runId, trace.nodeId, 'attempt-2-iteration-1'));
    expect(await readFile(file, 'utf8')).toBe('generated image bytes');
    expect(JSON.parse(output.outputs[0].valueJson).screens[0].asset_path).toBe(file);
    expect(await readFile(image, 'utf8')).toBe('generated image bytes');
    // A repeated completion reuses the content-addressed file without overwriting it.
    expect(JSON.parse(await task.finish(files({ image_path: image }, [image]))).artifacts[0].path).toBe(file);
  });

  it('allows an earlier generated image only when it was explicitly supplied to the task', async () => {
    const image = path.join(cache, 'earlier.png'); await writeFile(image, 'approved direction');
    const unrelated = await session();
    await expect(unrelated.finish(files({ image_path: image }, [image]))).rejects.toThrow('not generated by this task');
    const approved = await session(true, { concept: { asset_path: image } });
    const output = JSON.parse(await approved.finish(files({ image_path: image }, [image])));
    expect(await readFile(output.artifacts[0].path, 'utf8')).toBe('approved direction');
  });

  it('supports documents and data files already written in the project', async () => {
    const task = await session();
    for (const name of ['report.md', 'data.csv', 'workbook.xlsx', 'diagram.svg', 'document.pdf']) await writeFile(path.join(root, name), name);
    const names = ['report.md', 'data.csv', 'workbook.xlsx', 'diagram.svg', 'document.pdf'];
    const output = JSON.parse(await task.finish(files({ files: names }, names)));
    expect(output.artifacts).toHaveLength(5);
    for (const artifact of output.artifacts) expect(await readFile(artifact.path, 'utf8')).toBe(path.basename(artifact.path));
  });

  it('fails missing file claims and arbitrary paths outside the project', async () => {
    const task = await session();
    await expect(task.finish(result({}, [{ path: 'invented.pdf', description: 'Report' }]))).rejects.toMatchObject({ code: 'PROJECT_DELIVERABLE_INVALID' });
    const other = path.join(directory, 'private.txt'); await writeFile(other, 'private');
    await expect(task.finish(files({ file_path: other }, [other]))).rejects.toThrow('outside the approved project');
    expect(await readdir(root)).toEqual([]);
  });

  it('keeps read-only steps read-only while allowing existing file references and structured results', async () => {
    const task = await session(false); const image = path.join(cache, 'screen.png'); await writeFile(image, 'image');
    await expect(task.finish(files({ image_path: image }, [image]))).rejects.toThrow('workspace-write');
    await writeFile(path.join(root, 'existing.md'), 'existing');
    expect(JSON.parse(await task.finish(files({ file_path: 'existing.md' }, ['existing.md']))).artifacts).toHaveLength(1);
    expect(JSON.parse(await task.finish(result({ findings: ['No issues.'], summary: 'Read report.md' }))).artifacts).toEqual([]);
    expect(await readdir(root)).toEqual(['existing.md']);
  });

  it('rejects a destination junction that escapes the project before copying any file', async () => {
    const outside = path.join(directory, 'outside'); await mkdir(outside);
    await symlink(outside, path.join(root, 'artifacts'), process.platform === 'win32' ? 'junction' : 'dir');
    const task = await session(); const image = path.join(cache, 'screen.png'); await writeFile(image, 'image');
    await expect(task.finish(files({ image_path: image }, [image]))).rejects.toThrow('destination escapes');
    expect(await readdir(outside)).toEqual([]);
  });

  it('rejects generated-cache junctions and mismatched run identity', async () => {
    const outside = path.join(directory, 'outside'); await mkdir(outside);
    const task = await session(); await writeFile(path.join(outside, 'screen.png'), 'other project');
    await symlink(outside, path.join(cache, 'escape'), process.platform === 'win32' ? 'junction' : 'dir');
    const escaped = path.join(cache, 'escape', 'screen.png');
    await expect(task.finish(files({ image_path: escaped }, [escaped]))).rejects.toThrow('outside the configured artifact source');
    const wrong = JSON.parse(result({})); wrong.trace.runId = 'another-run';
    await expect(task.finish(JSON.stringify(wrong))).rejects.toThrow('trace does not match runId');
    expect(await readdir(root)).toEqual([]);
  });

  it('exports arbitrary declared file types, including extensionless files, without workflow-specific rules', async () => {
    const task = await session();
    const names = ['report.pdf', 'table.csv', 'book.xlsx', 'app.ts', 'clip.mp4', 'audio.wav', 'archive.zip', 'custom.unknownformat', 'LICENSE', '.gitignore'];
    const paths = names.map((name) => path.join(cache, name));
    for (const file of paths) await writeFile(file, Buffer.from([0, 1, 2, 255]));
    const output = JSON.parse(await task.finish(files({ arbitraryPayload: paths }, paths)));
    expect(output.artifacts).toHaveLength(names.length);
    expect(JSON.parse(output.outputs[0].valueJson).arbitraryPayload).toEqual(output.artifacts.map((artifact: { path: string }) => artifact.path));
    for (const artifact of output.artifacts) expect(await readFile(artifact.path)).toEqual(Buffer.from([0, 1, 2, 255]));
  });

  it('never guesses files from output field names or promotes an unconfigured source', async () => {
    const task = await session();
    const payload = { screens: ['home.png'], document: 'requirements.md', report: 'draft.pdf', file_path: 'not-a-file' };
    const output = JSON.parse(await task.finish(result(payload)));
    expect(output.artifacts).toEqual([]);
    expect(JSON.parse(output.outputs[0].valueJson)).toEqual(payload);
    const unconfigured = await createProjectDeliverables({ rootPath: root, writeAllowed: true, trace });
    const outside = path.join(cache, 'result.bin'); await writeFile(outside, 'tool output');
    await expect(unconfigured.finish(files({}, [outside]))).rejects.toThrow('configured artifact sources');
    expect(await readdir(root)).toEqual([]);
  });

  it('reads explicit local source configuration and fails closed for invalid configuration', async () => {
    const config = path.join(directory, 'artifact-sources.json');
    expect(await loadArtifactSourceRoots(config)).toEqual([]);
    await writeFile(config, JSON.stringify({ roots: [cache, cache] }));
    expect(await loadArtifactSourceRoots(config)).toEqual([cache]);
    await writeFile(config, JSON.stringify({ roots: [path.parse(cache).root] }));
    await expect(loadArtifactSourceRoots(config)).rejects.toThrow('not filesystem roots');
    await writeFile(config, JSON.stringify({ roots: ['relative-path'] }));
    await expect(loadArtifactSourceRoots(config)).rejects.toThrow('absolute folders');
    await writeFile(config, 'invalid json');
    await expect(loadArtifactSourceRoots(config)).rejects.toThrow();
  });
});
